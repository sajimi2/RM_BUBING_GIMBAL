// 可选浏览器验收：先运行 test_tuning_panel.py --serve-fixture，仅访问隔离的离线测试端口。
const path = require('node:path');
const fs = require('node:fs/promises');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '../..');
const {chromium} = require(process.env.PLAYWRIGHT_CORE || path.join(root, 'build/gui-qa/node_modules/playwright-core'));

(async () => {
  const browser = await chromium.launch({headless: true,
    executablePath: process.env.TEST_BROWSER || 'C:/Program Files/Google/Chrome/Application/chrome.exe'});
  const page = await browser.newPage({viewport: {width: 1440, height: 1050}, acceptDownloads: true});
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const waitText = (id, value) => page.waitForFunction(({id, value}) => document.getElementById(id).textContent.includes(value), {id, value});
  try {
    await page.goto('http://127.0.0.1:8766/', {waitUntil:'domcontentloaded'});
    await page.getByText('离线界面测试：', {exact:false}).waitFor();
    await page.locator('#port option[value="TEST-PORT"]').waitFor({state:'attached'});
    assert(await page.locator('#apply').isDisabled());
    assert(await page.locator('#send').isDisabled());
    await page.locator('#port').selectOption('TEST-PORT');
    await page.locator('#connect').click();
    await waitText('connection-badge', '已连接 · TEST-PORT');
    await waitText('gain-current', '-800');
    await waitText('notice', '握手成功');
    await waitText('ki-current', '0.00');
    await page.locator('#ki-input').fill('500');
    await waitText('ki-state', '输入待应用');
    assert.equal(await page.locator('#ki-current').textContent(), '0.00');
    await page.locator('#ki-apply').click();
    await waitText('ki-current', '500.00');
    assert.equal(await page.locator('#ki').textContent(), '500');
    await page.locator('#ki-zero').click();
    await waitText('ki-current', '0.00');
    await page.locator('#ki-input').fill('500');
    await page.locator('#ki-apply').click();
    await waitText('ki-current', '500.00');
    assert.equal(await page.locator('#gain-current').textContent(), '-800');
    assert(await page.locator('#send').isDisabled());
    await page.locator('#gain-down').click();
    assert.equal(await page.locator('#gain').inputValue(), '-900');
    await page.locator('#offset').fill('10');
    await page.locator('#apply').click();
    await waitText('notice', '读回确认');
    await waitText('gain-current', '-900');
    await waitText('offset-current', '10.00°');
    await page.locator('#zero').click();
    await waitText('gain-current', '0');
    await page.waitForFunction(() => !document.getElementById('restore').disabled);
    await page.locator('#restore').click();
    await waitText('gain-current', '-900');
    await page.locator('#uart').click();
    await waitText('source-badge', '串口模拟');
    await page.waitForFunction(() => !document.getElementById('send').disabled);
    await page.locator('#target').fill('5');
    await page.locator('#send').click();
    await waitText('target-value', '5.00°');
    // 测试夹具实际角度固定，界面不得编造“已到位”的机械响应。
    await waitText('actual-value', '1.15°');
    await page.locator('#record-start').click();
    await waitText('record-status', '正在记录');
    await page.waitForFunction(() => document.getElementById('record-status').textContent.match(/[1-9]\d* 点/));
    await page.locator('#mark').click();
    await waitText('notice', '保存一组');
    assert.equal(await page.locator('#records tr').count(), 1);
    assert((await page.locator('#records').innerText()).includes('-900'));
    await page.locator('#record-stop').click();
    await waitText('notice', '已停止记录');
    const downloadPromise = page.waitForEvent('download');
    await page.locator('#export').click();
    const download = await downloadPromise;
    const csvPath = path.join(root, 'build/gui-qa/recording.csv');
    await download.saveAs(csvPath);
    const csv = await fs.readFile(csvPath, 'utf8');
    assert(csv.includes('angle_error_rad') && csv.includes('TEST-PORT') && csv.includes('-900'));
    const firstRows = csv.replace(/^\uFEFF/, '').trim().split(/\r?\n/).map(line => line.split(','));
    const kiColumn = firstRows[0].indexOf('speed_ki');
    assert(firstRows.slice(1).every(row => Number(row[kiColumn]) === 500));
    // 第二轮必须从空缓冲开始，上一轮的 -900 不得混进新 CSV。
    await page.locator('#gain').fill('-700');
    await page.locator('#apply').click();
    await waitText('gain-current', '-700');
    await page.locator('#record-start').click();
    await waitText('notice', '上一轮连续记录已清空');
    await page.waitForFunction(() => document.getElementById('record-status').textContent.match(/[1-9]\d* 点/));
    await page.locator('#record-stop').click();
    await waitText('notice', '已停止记录');
    const roundDownload = page.waitForEvent('download');
    await page.locator('#export').click();
    const roundFile = await roundDownload;
    const roundPath = path.join(root, 'build/gui-qa/recording-round-2.csv');
    await roundFile.saveAs(roundPath);
    const roundRows = (await fs.readFile(roundPath, 'utf8')).replace(/^\uFEFF/, '').trim().split(/\r?\n/).map(line => line.split(','));
    const gainColumn = roundRows[0].indexOf('gain');
    assert(roundRows.length > 1 && roundRows.slice(1).every(row => Number(row[gainColumn]) === -700));
    await page.screenshot({path:path.join(root, 'build/gui-qa/desktop.png'), fullPage:true});
    await page.setViewportSize({width:390, height:844});
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1));
    await page.screenshot({path:path.join(root, 'build/gui-qa/mobile.png'), fullPage:true});
    await page.route('**/api/status*', route => route.abort());
    await waitText('notice', '本机服务未响应');
    assert(await page.locator('#send').isDisabled());
    assert(await page.locator('#apply').isDisabled());
    assert(await page.locator('#ki-apply').isDisabled());
    await page.unroute('**/api/status*');
    await waitText('connection-badge', '已连接 · TEST-PORT');
    // 旧固件仍能读原有参数，但 Ki 区域必须明确禁用。
    await page.route('**/api/status*', async route => {
      const response = await route.fetch(), data = await response.json();
      data.parameters = data.parameters.filter(p => p.id !== 3);
      await route.fulfill({response, json:data});
    });
    await waitText('ki-support', '烧录新版');
    assert(await page.locator('#ki-apply').isDisabled());
    assert(await page.locator('#ki-zero').isDisabled());
    await page.unroute('**/api/status*');
    await page.waitForFunction(() => !document.getElementById('ki-apply').disabled);
    await page.locator('#can').click();
    await waitText('source-badge', 'CAN 视觉');
    assert(await page.locator('#send').isDisabled());
    await page.locator('#disconnect').click();
    await waitText('notice', '已确认恢复 CAN');
    assert(await page.locator('#apply').isDisabled());
    await waitText('freshness', '保留最后读数');
    assert.deepEqual(errors, []);
    console.log('PASS: desktop/mobile UI; explicit connect/write/readback; degree conversion; zero/restore; UART/CAN target gates; real-state display; records and CSV; disconnect');
  } finally { await browser.close(); }
})().catch(error => {console.error(error); process.exitCode = 1;});
